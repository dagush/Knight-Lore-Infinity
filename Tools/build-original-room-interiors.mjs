import fs from 'fs';
import path from 'path';
import {fileURLToPath} from 'url';

import {
    getOriginalCharmRoomInterior,
    ORIGINAL_CHARM_ROOM_INTERIOR_COUNT,
} from '../SRC/runtime/knightlore-original-charm-rooms.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const mapPath = path.join(rootDir, 'SRC', 'static', 'maps', 'knight-lore-original-map.json');
const outPath = path.join(rootDir, 'SRC', 'runtime', 'knightlore-original-room-interiors.js');

const charmRoomIds = new Set(
    Array.from({length: ORIGINAL_CHARM_ROOM_INTERIOR_COUNT}, (_, index) => (
        getOriginalCharmRoomInterior(index).originalRoomId
    ))
);

const packPosition = position => (
    ((Number(position.z) & 0x03) << 6) |
    ((Number(position.y) & 0x07) << 3) |
    (Number(position.x) & 0x07)
);

const formatHex = value => `0x${(value & 0xff).toString(16).toUpperCase().padStart(2, '0')}`;

const main = () => {
    const document = JSON.parse(fs.readFileSync(mapPath, 'utf8'));
    const templates = document.rooms
        .filter(room => room.originalRoomId !== 0x88)
        .filter(room => !charmRoomIds.has(room.originalRoomId))
        .filter(room => room.blocks.some(block => block.positions.length))
        .map(room => [
            room.originalRoomId,
            room.size.selector,
            room.blocks.map(block => [
                block.type,
                block.positions.map(packPosition),
            ]),
        ])
        .sort((left, right) => left[0] - right[0]);

    const ids = templates.map(template => template[0]);
    if (new Set(ids).size !== ids.length) {
        throw new Error('Ordinary original-room catalogue contains duplicate room ids.');
    }
    if (ids.some(id => id === 0x88 || charmRoomIds.has(id))) {
        throw new Error('Ordinary original-room catalogue contains an excluded quest room.');
    }

    const source = `// Generated by Tools/build-original-room-interiors.mjs.
// Original room ids and selectors are provenance only. The procedural map owns
// topology, architecture, colour, theme, and physical room ids.
const RAW_ORIGINAL_ROOM_INTERIORS = ${JSON.stringify(templates)};

const unpackPosition = value => ({
    x: value & 0x07,
    y: (value >> 3) & 0x07,
    z: (value >> 6) & 0x03,
});

const decodedTemplates = RAW_ORIGINAL_ROOM_INTERIORS.map((entry, index) => {
    const [originalRoomId, originalSelector, runs] = entry;
    const blocks = runs.map(([type, positions]) => ({
        type,
        positions: positions.map(unpackPosition),
    }));
    return {
        index,
        originalRoomId,
        originalRoomHex: \`0x\${originalRoomId.toString(16).toUpperCase().padStart(2, '0')}\`,
        originalSelector,
        blocks,
        blockRunCount: blocks.length,
        blockObjectCount: blocks.reduce((total, run) => total + run.positions.length, 0),
        source: 'Knight Lore original location_tbl ordinary foreground block groups',
        architecturePolicy: 'generated exits, walls, size, colour, theme, and physical ids remain authoritative',
    };
});

const cloneData = value => JSON.parse(JSON.stringify(value));

export const ORIGINAL_ROOM_INTERIOR_COUNT = decodedTemplates.length;

export const getOriginalRoomInteriorCatalogue = () => cloneData(decodedTemplates);

export const getOriginalRoomInteriorByRoomId = roomId => {
    const normalized = Number(roomId) & 0xff;
    const template = decodedTemplates.find(item => item.originalRoomId === normalized);
    return template ? cloneData(template) : null;
};
`;

    fs.writeFileSync(outPath, source);
    const objectCount = templates.reduce((total, template) => (
        total + template[2].reduce((runTotal, run) => runTotal + run[1].length, 0)
    ), 0);
    console.log(
        `Wrote ${templates.length} ordinary interiors (${objectCount} foreground objects) to ` +
        `${path.relative(rootDir, outPath)}; excluded ${charmRoomIds.size} charm rooms and ${formatHex(0x88)}.`
    );
};

main();
